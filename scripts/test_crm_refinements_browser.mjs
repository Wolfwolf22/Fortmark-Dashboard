/** Local synthetic UI only. Never accepts a remote origin, cookies or a user profile. */
import assert from "node:assert/strict";
import { chromium } from "playwright-core";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const origin = process.argv[2] ?? "http://127.0.0.1:4176", output = resolve(process.argv[3] ?? "../outputs/crm-refinements-browser");
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin)) throw Error("Synthetic preview must use a loopback origin");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const checks = [], errors = [];
const check = (name, ok) => { assert(ok, name); checks.push(name); console.log("PASS " + name); };
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
  page.setDefaultTimeout(12000);
  page.on("pageerror", error => errors.push(error.message));
  // The preview's adapters intercept all data access; prohibit accidental external requests.
  await page.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const open = async view => { await page.goto(`${origin}/preview?${new URLSearchParams({ view, scenario: "interactive" })}`); };
  const sections = () => page.locator("[data-transaction-section]").evaluateAll(nodes => nodes.map(node => node.getAttribute("data-transaction-section")));
  await open("/transactions/sample-diligence");
  await page.getByRole("button", { name: "Customize layout", exact: true }).waitFor();
  const before = await sections();
  check("all buyer cards are individually registered without listing-only sections", before.includes("stage-checklist") && before.includes("vendors") && before.includes("showing-tours") && !before.includes("open-houses"));
  await page.getByRole("button", { name: "Customize layout", exact: true }).click();
  await page.getByRole("button", { name: "Move Vendors earlier", exact: true }).click();
  const after = await sections();
  check("explicit move changes order once without removing any card", after.indexOf("vendors") === before.indexOf("vendors") - 1 && [...after].sort().join() === [...before].sort().join());
  check("moving retains the focused control", await page.getByRole("button", { name: "Move Vendors earlier", exact: true }).evaluate(node => node === document.activeElement));
  const handle = page.getByRole("button", { name: "Drag Stage checklist", exact: true });
  await handle.scrollIntoViewIfNeeded(); await handle.focus(); await page.keyboard.press("Space");
  await page.waitForFunction(() => document.querySelector('[aria-label="Drag Stage checklist"]')?.getAttribute("aria-pressed") === "true");
  // Let dnd-kit attach its deferred keyboard listener after activation.
  await page.waitForTimeout(200);
  await page.keyboard.press("ArrowUp");
  await page.waitForFunction(() => Array.from(document.querySelectorAll('[aria-live="assertive"]')).some(node => node.textContent.includes("over droppable area showing-tours")));
  await page.keyboard.press("Space");
  await page.waitForFunction(() => document.querySelector('[aria-label="Drag Stage checklist"]')?.getAttribute("aria-pressed") !== "true");
  check("keyboard drag rearranges a card while preserving the full set", (await sections()).join() !== after.join() && (await sections()).length === before.length);
  await page.getByRole("button", { name: "Done arranging", exact: true }).click();
  await page.getByRole("button", { name: "Edit details", exact: true }).click();
  await page.getByRole("dialog").waitFor();
  const help = page.getByRole("button", { name: /Help with Commission rate/i });
  await help.focus();
  await page.getByRole("tooltip").waitFor();
  check("commission help is available to keyboard focus", /gross|percent|rate|price/i.test(await page.getByRole("tooltip").innerText()));
  await page.getByRole("dialog").getByRole("button", { name: "Cancel", exact: true }).click();
  await page.locator("#transaction-vendors").getByRole("combobox", { name: "Choose Inspector", exact: true }).click();
  await page.getByRole("option", { name: /Sample Coast Inspections/ }).click();
  await page.getByRole("button", { name: "Confirm selection", exact: true }).click();
  const inspector = page.locator("#transaction-vendors").locator("div.rounded-panel").filter({ has: page.getByText("Inspector", { exact: true }) });
  await inspector.getByRole("button", { name: "Full detail", exact: true }).click();
  await page.getByLabel("Service date", { exact: true }).fill("2026-11-06");
  await page.getByLabel("Cost ($)", { exact: true }).fill("225.50");
  await page.getByRole("button", { name: "Save details", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Close", exact: true }).last().click();
  await inspector.getByText("$225.50", { exact: true }).waitFor();
  check("saved vendor figures appear on the tile immediately", (await inspector.innerText()).includes("Nov 6, 2026"));
  await page.getByRole("button", { name: "Link MLS property", exact: true }).click();
  await page.getByRole("dialog", { name: "Find MLS property", exact: true }).getByLabel("MLS number", { exact: true }).fill("SAMPLE-001");
  await page.getByRole("button", { name: "Find property", exact: true }).click();
  await page.getByRole("button", { name: "Link reviewed property", exact: true }).click();
  await page.getByRole("dialog", { name: "Find MLS property", exact: true }).waitFor({ state: "hidden" });
  await page.locator("#transaction-vendors").getByRole("combobox", { name: "Choose Mortgage / financing", exact: true }).click();
  await page.getByRole("option", { name: /Sample Harbor Mortgage/ }).click();
  await page.getByRole("button", { name: "Confirm selection", exact: true }).click();
  const mortgage = page.locator("#transaction-vendors").locator("div.rounded-panel").filter({ has: page.getByText("Mortgage / financing", { exact: true }) });
  await mortgage.getByRole("button", { name: "Full detail", exact: true }).click();
  await page.getByRole("button", { name: "Review MLS figures", exact: true }).click();
  await page.getByText("Property tax · $820.83 / month", { exact: true }).waitFor();
  check("MLS review displays annual tax divided by twelve and stated monthly HOA", (await page.getByRole("region", { name: "Review MLS monthly figures", exact: true }).innerText()).includes("HOA · $325.00 / month"));
  await page.locator("summary").filter({ hasText: /^Recorded monthly figures$/ }).click();
  await page.getByLabel("HOA ($ / month)", { exact: true }).fill("411.25");
  await page.getByRole("button", { name: "Fill 1 blank monthly field", exact: true }).click();
  check("MLS suggestions fill only blank fields and preserve a typed HOA amount", await page.getByLabel("Property tax ($ / month)", { exact: true }).inputValue() === "820.83" && await page.getByLabel("HOA ($ / month)", { exact: true }).inputValue() === "411.25");
  await page.getByRole("button", { name: "Save details", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Close", exact: true }).last().click();
  await mortgage.getByText("$820.83", { exact: true }).waitFor();
  check("saved tax and manually entered HOA appear on the mortgage vendor tile", (await mortgage.innerText()).includes("$411.25"));
  await mortgage.screenshot({ path: resolve(output, "mortgage-recorded-figures.png") });
  await page.screenshot({ path: resolve(output, "transaction-vendor.png"), fullPage: true });
  await page.getByRole("link", { name: "Transactions", exact: true }).first().click();
  await page.getByRole("button", { name: "New transaction", exact: true }).click();
  const wizard = page.getByRole("dialog", { name: "New transaction", exact: true });
  await wizard.getByLabel("Property address", { exact: true }).fill("Synthetic protected draft address");
  await page.mouse.click(6, 360); await page.keyboard.press("Escape");
  check("outside click and Escape preserve the transaction wizard and draft", await wizard.getByLabel("Property address", { exact: true }).inputValue() === "Synthetic protected draft address");
  await wizard.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("dialog", { name: "Discard this transaction draft?", exact: true }).getByRole("button", { name: "Keep editing", exact: true }).click();
  check("explicit Keep editing retains the same form draft", await wizard.getByLabel("Property address", { exact: true }).inputValue() === "Synthetic protected draft address");
  await wizard.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("button", { name: "Discard draft", exact: true }).click();
  check("only deliberate discard closes the transaction wizard", await page.getByRole("dialog", { name: "New transaction", exact: true }).count() === 0);
  await open("/contacts?open=sample-due-today");
  await page.getByRole("button", { name: "Touch history", exact: true }).waitFor();
  check("legacy note block is removed and recent touch is inside Next action", !(await page.locator("body").innerText()).includes("Legacy note") && (await page.getByRole("region", { name: "Next action", exact: true }).innerText()).includes("Most recent touch"));
  await page.getByRole("button", { name: "Touch history", exact: true }).click();
  await page.getByRole("heading", { name: /Touch history ·/ }).waitFor();
  check("touch history opens a contact-specific detailed dialog", (await page.getByRole("dialog").innerText()).includes("Sample Due Today"));
  await page.getByRole("dialog").getByRole("button", { name: "Close", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(output, "contact-390.png"), fullPage: true });
  check("contact remains within the phone viewport", await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await open("/transactions/sample-diligence");
  await page.getByRole("button", { name: "Customize layout", exact: true }).click();
  await page.screenshot({ path: resolve(output, "layout-390.png"), fullPage: true });
  check("custom layout remains within the phone viewport", await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  check("no uncaught browser errors", errors.length === 0);
  await writeFile(resolve(output, "results.json"), JSON.stringify({ ok: true, checks, errors, data: "synthetic only; all data reset on reload", origin }, null, 2));
} catch (error) {
  await writeFile(resolve(output, "failure.json"), JSON.stringify({ checks, errors, error: String(error) }, null, 2)); throw error;
} finally { await browser.close(); }
